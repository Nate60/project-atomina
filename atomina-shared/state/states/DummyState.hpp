#pragma once
#include "core/api.hpp"
#include "state/BaseState.hpp"

namespace ATMA
{
    /**
     * Dummy state used as a place holder
     */
    class DummyState: public BaseState
    {
    public:
        // default constructor
        DummyState(ATMAContext *l_ctx);

        // deconstructor
        virtual ~DummyState();

        /**
         * stub function for activation of state
         */
        virtual void activate(ATMAContext *l_ctx) override;

        /**
         * stub function for deactivation of state
         */
        virtual void deactivate(ATMAContext *l_ctx) override;

        /**
         * gives type id of dummy state
         * @return type id of dummy state
         */
        virtual unsigned int getId() const override
        {
            return StateType(State::Dummy);
        }

        /**
         * passes window events to be handled by the state
         * @param l_winEvent the event generated by the window
         * @returns whether or not the event was handled
         */
        virtual void handleInput(ATMAContext *l_ctx, const WindowEvent &l_winEvent) override {}
    };
}
